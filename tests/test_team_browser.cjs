// Runs against an isolated service with first-run setup available.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {randomBytes} = require('node:crypto');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {openRegistration} = require('./layout-browser-helpers.cjs');
const [origin, evidence] = process.argv.slice(2);

async function run() {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const operator = await browser.newContext({viewport:{width:1440,height:900}});
    const operatorTab = await operator.newPage();
    const visitor = await browser.newContext({viewport:{width:390,height:844}});
    const mobile = await visitor.newPage();
    const guestRequests = [], errors = [];
    mobile.on('request', req => guestRequests.push(new URL(req.url()).pathname));
    for(const page of [operatorTab,mobile])page.on('pageerror',err=>errors.push(err.message));
    await operatorTab.goto(origin);
    const login = operatorTab.locator('form').filter({has:operatorTab.locator('input[type=password]')});
    await login.locator('input:not([type=password]):not([type=hidden])').first().fill('browser-owner');
    const password = randomBytes(24).toString('hex');
    for(const field of await login.locator('input[type=password]').all())await field.fill(password);
    await login.getByRole('button',{name:'创建账号并登录'}).click();
    await operatorTab.locator('[data-op=copy][data-id=caiyun2025]').waitFor();
    assert.doesNotMatch(await operatorTab.locator('body').innerText(),/改稿|导出给 AI|活动包/);
    await operatorTab.locator('[data-op=copy][data-id=caiyun2025]').click();
    await operatorTab.locator('#new-event input').fill('未来协作创新峰会');
    const created = operatorTab.waitForResponse(r => new URL(r.url()).pathname==='/api/events' && r.request().method()==='POST');
    await operatorTab.locator('button[form=new-event]').click();
    const {id} = await (await created).json();
    const api = '/api/events/'+id;
    const editor = operatorTab.locator('#zb-editor');
    await editor.locator('[data-field=date]').waitFor();
    assert(await editor.evaluate(n=>n.parentElement.id==='workspace'&&getComputedStyle(n).position!=='fixed'));
    await editor.locator('.zc-screen .il-element').first().waitFor();
    if(evidence){fs.mkdirSync(evidence,{recursive:true});await operatorTab.screenshot({path:path.join(evidence,'basic-panel.jpg'),quality:86,animations:'disabled'});}
    assert.doesNotMatch(await editor.innerText(), /改稿|导出给 AI|活动包/);
    assert.equal((await visitor.request.get(origin+'/api/public/'+id)).status(),404);
    await editor.getByRole('button',{name:'活动日期',exact:true}).click();
    await operatorTab.locator('.ui-calendar-grid').waitFor();
    await operatorTab.keyboard.press('Escape');
    assert.equal(await operatorTab.locator('.ui-popover').count(),0);
    await editor.getByRole('button',{name:'活动日期',exact:true}).click();
    const directDate=operatorTab.getByRole('textbox',{name:'输入日期（年-月-日）'});
    await directDate.fill('2026-02-31');
    assert.equal(await operatorTab.getByRole('button',{name:'应用',exact:true}).isEnabled(),false);
    await directDate.fill('2026-12-19');
    await directDate.press('Enter');
    await operatorTab.locator('[data-nav=records]').click();
    await operatorTab.getByRole('button',{name:'继续编辑'}).click();
    await operatorTab.waitForFunction(()=>location.hash.startsWith('#edit/'));
    assert.equal(await editor.locator('[data-field=date]').inputValue(),'2026-12-19');
    assert.equal(await editor.locator('[data-template], [data-device-preset]:visible').count(),0);
    await editor.getByRole('button',{name:'逐屏设计',exact:true}).click();
    await editor.locator('[data-ds-tool=paragraph]').click();
    await editor.locator('[data-tab=form]').click();
    await editor.locator('[data-act=add-field]').click();
    await editor.locator('input[data-field-index]').last().fill('职位');
    const saved=operatorTab.waitForResponse(r=>new URL(r.url()).pathname===api && r.request().method()==='PUT');
    await editor.locator('[data-act=save]').click();
    const savedResponse=await saved;
    assert.equal(savedResponse.status(),200);
    const draft=await savedResponse.json();
    assert.equal(draft.template,'invitation');
    assert(draft.design.pages.some(p=>p.elements.some(e=>e.type==='paragraph')));
    assert.equal(draft.date,'2026-12-19');
    assert.equal(draft.fields.at(-1).label,'职位');
    assert.equal(draft.fields.at(-1).required,false);
    assert.equal((await visitor.request.get(origin+'/api/public/'+id)).status(),404);
    await editor.getByText('创建人 browser-owner',{exact:true}).waitFor();
    await editor.getByRole('button',{name:'操作日志',exact:true}).click();
    const logs=operatorTab.getByRole('dialog',{name:'活动操作日志'});
    await logs.getByText('保存草稿',{exact:true}).waitFor();
    await logs.getByText('复制为新一期',{exact:true}).waitFor();
    await logs.getByRole('button',{name:'关闭'}).click();
    await operatorTab.locator('[data-act=publish]').click();
    const publishDialog=operatorTab.getByRole('dialog',{name:'确认发布',exact:true});
    await publishDialog.getByText('报名字段',{exact:true}).waitFor();
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'publish-review.jpg'),quality:88,animations:'disabled'});
    await publishDialog.getByRole('button',{name:'取消'}).click();
    assert.equal((await visitor.request.get(origin+'/api/public/'+id)).status(),404);
    await editor.locator('[data-act=publish]').click();
    await publishDialog.getByRole('button',{name:'确认发布'}).click();
    await operatorTab.locator('#zb-editor').waitFor({state:'detached'});
    const sharedUrl=await operatorTab.locator('.s-dialog input[readonly]').inputValue();
    assert.equal(new URL(sharedUrl).origin,origin);
    assert.match(new URL(sharedUrl).pathname,/^\/s\/[A-Za-z0-9]{8}$/);
    const file=operatorTab.waitForEvent('download');
    await operatorTab.getByRole('link',{name:'下载二维码'}).click();
    assert.match((await file).suggestedFilename(),/^invite-[A-Za-z0-9]{8}\.png$/);
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'publish-share.jpg'),quality:88,animations:'disabled'});
    await operatorTab.locator('.s-dialog [data-op=dismiss]').first().click();
    await mobile.goto(sharedUrl);
    await openRegistration(mobile);
    await mobile.locator('input[name=company]').fill('验收企业');
    await mobile.locator('input[name=name]').fill('测试来宾');
    await mobile.getByLabel('职位').fill('参会代表');
    await mobile.locator('#zb-invite button[type=submit]').click();
    await mobile.locator('.ze-done').waitFor();
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=390),true);
    assert(!guestRequests.includes('/api/workspace'));
    assert.equal((await visitor.request.get(origin+'/api/workspace')).status(),401);
    await operatorTab.locator('[data-nav=records]').click();
    await operatorTab.locator('.data-index-table').waitFor();
    const eventRow=operatorTab.locator('.data-index-table tr').filter({hasText:'未来协作创新峰会'});
    const details=eventRow.getByRole('link',{name:/查看.*详情/});
    await details.waitFor();
    await eventRow.locator('[data-col=浏览量]').filter({hasText:/^1$/}).waitFor();
    assert.equal(await eventRow.locator('[data-col=成功报名]').textContent(),'1');
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'activity-list.jpg'),quality:87,animations:'disabled'});
    await details.click();
    await operatorTab.locator('.metrics-strip').waitFor();
    const numbers=await operatorTab.locator('.metrics-strip dd').allTextContents();
    assert.equal(numbers[0],'1');assert.equal(numbers[1],'1');assert.equal(numbers[4],'1');assert.equal(numbers[5],'100.0%');
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'activity-data.jpg'),quality:87,animations:'disabled'});
    await operatorTab.getByRole('cell',{name:'验收企业',exact:true}).waitFor();
    await operatorTab.locator('[data-op=detail]').click();
    await operatorTab.getByText('参会代表',{exact:true}).waitFor();
    if(evidence){
      fs.mkdirSync(evidence,{recursive:true});
      await operatorTab.screenshot({path:path.join(evidence,'manual-registration.jpg'),animations:'disabled',quality:87});
    }
    await operatorTab.locator('.s-dialog [data-op=dismiss]').click();
    await operatorTab.locator('.data-breadcrumb a').click();
    await operatorTab.locator('.data-index-table').waitFor();
    await operatorTab.getByRole('combobox',{name:'统计时间范围'}).click();
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'activity-filter.jpg'),quality:87,animations:'disabled'});
    await operatorTab.getByRole('option',{name:'近 7 天'}).click();
    await operatorTab.locator('[data-nav=home]').click();
    await operatorTab.locator('.library').waitFor();
    await operatorTab.locator('[data-op=edit][data-id="'+id+'"]').last().click();
    const locationField=editor.locator('[data-field=place]');
    const originalPlace=await locationField.inputValue();
    await locationField.fill('待发布的新会场');
    await editor.locator('[data-act=save]').click();
    await editor.getByText('有待发布修改',{exact:true}).waitFor();
    await editor.locator('[data-act=publish]').click();
    const updateReview=operatorTab.getByRole('dialog',{name:'确认更新发布版',exact:true});
    await updateReview.getByText('原地点',{exact:true}).waitFor();
    await updateReview.getByText(originalPlace,{exact:true}).waitFor();
    await updateReview.getByText('待发布的新会场',{exact:true}).waitFor();
    await updateReview.getByRole('button',{name:'取消'}).click();
    assert.equal((await (await visitor.request.get(origin+'/api/public/'+id)).json()).place,originalPlace);
    await editor.locator('[data-act=exit]').click();
    await operatorTab.locator('.library').waitFor();
    await operatorTab.locator('[data-op=share][data-id="'+id+'"]').last().click();
    async function changeStatus(label,expected){
      await operatorTab.locator('.publication-controls').getByRole('button',{name:label,exact:true}).click();
      await operatorTab.locator('.ui-confirm').getByRole('button',{name:label,exact:true}).click();
      await operatorTab.locator('.publication-dialog-status').getByText(expected,{exact:true}).waitFor();
    }
    await changeStatus('关闭报名','报名已关闭');
    assert.equal((await mobile.reload()).status(),200);
    assert.equal((await (await visitor.request.get(origin+'/api/public/'+id)).json()).status,'ended');
    await changeStatus('下线邀请函','已下线');
    assert.equal((await mobile.reload()).status(),410);
    await mobile.getByRole('heading',{name:'邀请函已下线'}).waitFor();
    await changeStatus('恢复上线','报名已关闭');
    assert.equal(await operatorTab.locator('.s-dialog input[readonly]').inputValue(),sharedUrl);
    await changeStatus('重新开放报名','报名中');
    await operatorTab.locator('.s-dialog [data-op=dismiss]').first().click();
    for (let i=1;i<=7;i++){
      const fixture={...draft,id:'pagination'+i,version:0,status:'draft',title:'分页验收活动 '+i};
      const saved=await operator.request.post(origin+'/api/events',{data:{event:fixture},headers:{Origin:origin}});
      assert.equal(saved.status(),201);
      if(i===7){
        const other=await saved.json();
        const published=await operator.request.post(origin+'/api/events/'+other.id+'/publish',{data:{event:other},headers:{Origin:origin}});
        assert.equal(published.status(),200);
      }
    }
    await operatorTab.reload();
    await operatorTab.locator('.tiles').waitFor();
    assert.equal(await operatorTab.locator('.tile').count(),6);
    await operatorTab.getByRole('button',{name:'列表',exact:true}).click();
    assert.equal(await operatorTab.locator('.lib-table tbody tr').count(),6);
    await operatorTab.getByRole('button',{name:'下一页',exact:true}).click();
    assert.equal(await operatorTab.locator('.lib-table tbody tr').count(),3);
    await operatorTab.getByRole('searchbox',{name:'搜索活动名称'}).fill('分页验收活动 1');
    assert.equal(await operatorTab.locator('.lib-table tbody tr').count(),1);
    assert.match(await operatorTab.locator('.lib-table').innerText(),/分页验收活动 1/);
    await operatorTab.getByRole('searchbox',{name:'搜索活动名称'}).fill('');
    const spotlightTitle=operatorTab.locator('#home-spotlight h2');
    const before=await spotlightTitle.innerText();
    await operatorTab.mouse.move(10,10);
    await operatorTab.waitForFunction(title=>document.querySelector('#home-spotlight h2')?.textContent!==title,before);
    const rotated=await spotlightTitle.innerText();
    await operatorTab.getByRole('button',{name:'下一场活动',exact:true}).click();
    assert.notEqual(await spotlightTitle.innerText(),rotated);
    if(evidence)await operatorTab.screenshot({path:path.join(evidence,'activity-library.jpg'),quality:87,animations:'disabled'});
    for(const width of [768,390]){
      await operatorTab.setViewportSize({width,height:844});
      await operatorTab.locator('[data-nav=records]').click();
      await operatorTab.locator('.data-index-table').waitFor();
      await operatorTab.locator('.data-index-table [data-col=成功报名]').first().filter({hasText:/^0$/}).waitFor();
      assert(await operatorTab.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      if(evidence)await operatorTab.screenshot({path:path.join(evidence,'activity-list-'+width+'.jpg'),quality:84,animations:'disabled'});
      await operatorTab.locator('[data-nav=home]').click();
      await operatorTab.locator('.library').waitFor();
      assert(await operatorTab.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      await operatorTab.goto(origin+'/#edit/'+id);
      await editor.locator('.zc-screen .il-element').first().waitFor();
      assert(await editor.evaluate(n=>n.getBoundingClientRect().width<=innerWidth&&document.documentElement.scrollWidth<=innerWidth));
      await editor.locator('[data-tab=form]').click();
      assert(await editor.evaluate(n=>n.getBoundingClientRect().width<=innerWidth&&document.documentElement.scrollWidth<=innerWidth));
    }
    assert.deepEqual(errors,[]);
    console.log('Verified setup, shared copy, manual edits and draft isolation, publication, isolated public signup and record details.');
  } finally {await browser.close();}
}
run().catch(error=>{console.error(error);process.exitCode=1;});
